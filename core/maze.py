def cari_posisi(peta):
    posisi ={}
    for r, baris in enumerate(peta):
        for c, ch in enumerate(baris):
            if ch in  "DHBE":
                posisi[ch] = (r,c)
    return posisi


def bisa_dilewati(peta, r, c):
    if not(0 <= r < 18 and 0 <= c < 32):
        return False
    return peta[r][c] != "#"

